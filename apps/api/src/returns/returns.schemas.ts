import type { ApiResponseSchemaHost } from '@nestjs/swagger';
type Schema = ApiResponseSchemaHost['schema'];
const text: Schema = { type: 'string' },
  uuid: Schema = { type: 'string', format: 'uuid' },
  money: Schema = {
    type: 'string',
    nullable: true,
    example: '125.0000',
    description: 'Exact decimal; null without finance.view.',
  },
  timestamp: Schema = { type: 'string', format: 'date-time' },
  boolean: Schema = { type: 'boolean' };
const obj = (properties: Record<string, Schema>): Schema => ({ type: 'object', properties });
const array = (items: Schema): Schema => ({ type: 'array', items });
const person = obj({ id: uuid, name: text, isActive: boolean });
const source = obj({
  id: uuid,
  sequenceNumber: { type: 'integer' },
  number: text,
  customer: { ...person, nullable: true },
  location: { ...person, nullable: true },
});
const returnFields = {
  id: uuid,
  number: text,
  sequenceNumber: { type: 'integer' },
  status: { type: 'string', enum: ['DRAFT', 'POSTED', 'CANCELLED'] },
  salesOrder: source,
  currencyCode: text,
  totalRefundableAmount: money,
  refundedForReturn: money,
  remainingReturnCredit: money,
  itemsCount: { type: 'integer' },
  createdAt: timestamp,
  postedAt: { ...timestamp, nullable: true },
};
const refundFields = {
  id: uuid,
  number: text,
  sequenceNumber: { type: 'integer' },
  salesOrder: source,
  amount: money,
  currencyCode: text,
  paymentDate: { type: 'string', format: 'date' },
  paymentMethod: { type: 'string', enum: ['CASH', 'CARD', 'BANK_TRANSFER', 'OTHER'] },
  reference: { ...text, nullable: true },
  createdAt: timestamp,
};
export const returnsSchemas = {
  list: obj({ items: array(obj(returnFields)), nextCursor: { ...text, nullable: true } }),
  detail: obj({
    ...returnFields,
    financeVisible: boolean,
    reason: { ...text, nullable: true },
    note: { ...text, nullable: true },
    revision: { type: 'integer' },
    createdBy: obj({ id: uuid }),
    postedBy: { ...obj({ id: uuid }), nullable: true },
    updatedAt: timestamp,
    cancelledAt: { ...timestamp, nullable: true },
    cancelledBy: { ...obj({ id: uuid }), nullable: true },
    cancelReason: { ...text, nullable: true },
    collectedAmount: money,
    refundedAmount: money,
    availableRefundAmount: money,
    currentQuoteAmount: money,
    quoteValid: boolean,
    inventoryTransactionId: { ...uuid, nullable: true },
    refunds: { ...array(obj(refundFields)), nullable: true },
    refundsTruncated: boolean,
    items: array(
      obj({
        id: uuid,
        salesOrderItemId: uuid,
        variantId: uuid,
        quantity: { type: 'string', example: '1.000000' },
        restockDisposition: { type: 'string', enum: ['RESTOCK', 'NO_RESTOCK'] },
        location: { ...person, nullable: true },
        refundAmount: money,
        stockRestocked: boolean,
        snapshotItemName: text,
        snapshotVariantName: { ...text, nullable: true },
        snapshotSku: { ...text, nullable: true },
        snapshotUnit: text,
        snapshotItemType: { type: 'string', enum: ['PRODUCT', 'SERVICE'], nullable: true },
      }),
    ),
  }),
  refunds: obj({ items: array(obj(refundFields)), nextCursor: { ...text, nullable: true } }),
  refund: obj({
    ...refundFields,
    note: { ...text, nullable: true },
    createdBy: obj({ id: uuid }),
    allocations: array(obj({ salesReturnId: uuid, returnNumber: text, allocatedAmount: money })),
  }),
  eligibility: obj({
    salesOrder: source,
    currencyCode: text,
    financeVisible: boolean,
    postedReturnsCount: { type: 'integer' },
    postedReturnCredits: money,
    collectedAmount: money,
    refundedAmount: money,
    remainingRefundableCashCap: money,
    unusedReturnCredit: money,
    availableRefundAmount: money,
    adjustedSalesAmount: money,
    netOutstandingAmount: money,
    netPaidAmount: money,
    items: array(
      obj({
        salesOrderItemId: uuid,
        variantId: uuid,
        snapshotItemName: text,
        snapshotVariantName: { ...text, nullable: true },
        snapshotSku: { ...text, nullable: true },
        snapshotUnit: text,
        snapshotItemType: { type: 'string', enum: ['PRODUCT', 'SERVICE'], nullable: true },
        stockDeducted: boolean,
        restockAllowed: boolean,
        soldQuantity: text,
        returnedQuantity: text,
        remainingQuantity: text,
        originalLineAmount: money,
        creditedAmount: money,
        remainingCredit: money,
      }),
    ),
  }),
};
